        public static Texture2D Get(string name)
        {
            Texture2D t;
            if (cache.TryGetValue(name, out t) && t != null) return t;
            string[] map;
            if (!Maps.TryGetValue(name, out map)) map = new[] { ".........", ".........", ".........", "..#####..", "..#####..", "..#####..", ".........", ".........", "........." };
            t = new Texture2D(9, 9, TextureFormat.RGBA32, false);
            t.filterMode = FilterMode.Point;
            t.wrapMode = TextureWrapMode.Clamp;
            Color32[] px = new Color32[81];
            for (int row = 0; row < 9; row++)
                for (int col = 0; col < 9; col++)
                    px[(8 - row) * 9 + col] = map[row][col] == '#' ? Gold : new Color32(0, 0, 0, 0);
            t.SetPixels32(px);
            t.Apply(false);
            cache[name] = t;
            return t;
        }
